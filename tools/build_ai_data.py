def read(name):
    with io.open(os.path.join(TXT, name), 'r', encoding='utf-8') as f:
        return [l.strip().strip('\u3000') for l in f.read().split('\n') if l.strip()]

def clean(t):
    return t.replace('\u3000', '').strip()

